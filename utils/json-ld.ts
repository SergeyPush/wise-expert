/**
 * Сериализация JSON-LD для вставки в <script type="application/ld+json">.
 *
 * `JSON.stringify` не экранирует `<` и `>`, поэтому текст из Contentful,
 * содержащий `</script>`, закрывает тег, и всё, что идёт следом, браузер
 * разбирает как разметку. Ответ FAQ или отзыв клиента — обычный редакторский
 * ввод, так что полагаться на «в CMS такого не напишут» нельзя.
 *
 * Заменяем опасные символы на \u-последовательности: внутри JSON они означают
 * ровно те же символы, но парсер HTML тега в них уже не видит. Кроме скобок и
 * амперсанда экранируем U+2028/U+2029 — в JS это переводы строки, на которых
 * ломается разбор самого скрипта.
 *
 * Шаблон собран через RegExp из строки, а не литералом: литеральные U+2028 и
 * U+2029 в исходнике — те же переводы строки, и регулярное выражение с ними
 * не компилируется.
 */
const UNSAFE_IN_SCRIPT = new RegExp('[<>&\\u2028\\u2029]', 'g');

export const jsonLd = (data: unknown): string =>
  JSON.stringify(data).replace(
    UNSAFE_IN_SCRIPT,
    (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
